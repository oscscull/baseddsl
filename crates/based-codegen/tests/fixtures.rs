//! Typed test fixtures: which columns a builder sets, and the Rust and TypeScript builders
//! generated from that one reading.

use based_ast::FileId;
use based_codegen::client::{client_with, typescript_fixtures, ClientOptions, ClientTarget};
use based_codegen::fixture::{fixture_model, Placeholder, Role};
use based_parser::parse_file;
use based_sema::{check, CheckedSchema};

const SCHEMA: &str = r#"
scope Tenant (org: Org = $ctx.org)
enum Tier { free, pro }

Org { id: Id, name: text, slug: text (unique), tier: Tier, active: bool (default true) }

@created(created_at)
@soft_delete(deleted_at)
@scope Tenant
Note {
  id: Id
  org: Org
  reviewer: Org?
  title: text
  body: text?
  due: date
  created_at: timestamp
  deleted_at: timestamp?
  shout = title || "!"
}

Mesh { id: Id, shape: raw("geometry") }
Legacy { id: Id, shape: raw("geometry")? }
"#;

fn schema() -> (CheckedSchema, Vec<based_ast::Decl>) {
    let sf = parse_file(SCHEMA, FileId(0)).unwrap_or_else(|d| panic!("parse failed: {d:#?}"));
    let (schema, diags) = check(&sf.decls);
    let errors: Vec<_> = diags
        .iter()
        .filter(|d| d.severity == based_diagnostics::Severity::Error)
        .map(|d| (d.code, d.message.clone()))
        .collect();
    assert!(errors.is_empty(), "unexpected sema errors: {errors:?}");
    (schema, sf.decls)
}

fn role(schema: &CheckedSchema, model: &str, field: &str) -> Option<Role> {
    let model = schema.model(model).unwrap();
    let fixture = fixture_model(schema, model).unwrap();
    fixture.field(field).map(|f| f.role.clone())
}

#[test]
fn required_columns_get_placeholders_and_relations_are_arguments() {
    let (schema, _) = schema();
    assert_eq!(
        role(&schema, "Note", "title"),
        Some(Role::Placeholder(Placeholder::Text))
    );
    assert_eq!(
        role(&schema, "Note", "due"),
        Some(Role::Placeholder(Placeholder::Date))
    );
    assert_eq!(role(&schema, "Note", "org"), Some(Role::Argument));
    assert_eq!(role(&schema, "Note", "reviewer"), Some(Role::Optional));
    assert_eq!(role(&schema, "Note", "body"), Some(Role::Optional));
    assert_eq!(
        role(&schema, "Note", "id"),
        Some(Role::Optional),
        "the engine mints ids"
    );
    assert_eq!(
        role(&schema, "Note", "created_at"),
        Some(Role::Optional),
        "stamped when unset"
    );
    assert_eq!(
        role(&schema, "Org", "active"),
        Some(Role::Optional),
        "defaulted"
    );
    assert!(matches!(
        role(&schema, "Org", "tier"),
        Some(Role::Placeholder(Placeholder::Enum(_)))
    ));
    assert_eq!(
        role(&schema, "Note", "shout"),
        None,
        "generated columns are never set"
    );
    assert_eq!(
        role(&schema, "Note", "deleted_at"),
        None,
        "fixtures are live rows"
    );
}

#[test]
fn a_required_opaque_column_cannot_be_a_fixture() {
    let (schema, _) = schema();
    let mesh = schema.model("Mesh").unwrap();
    let why = fixture_model(&schema, mesh).err().unwrap();
    assert!(why.contains("shape"), "{why}");
    let legacy = schema.model("Legacy").unwrap();
    assert!(
        fixture_model(&schema, legacy).is_ok(),
        "an optional opaque column is skipped"
    );
}

#[test]
fn every_rust_client_carries_fixtures() {
    let (schema, decls) = schema();
    let embedded = ClientOptions {
        embedded: true,
        dialect: None,
    };
    let out = client_with(&schema, &decls, ClientTarget::Rust, embedded);
    assert!(out.contains("pub mod fixtures {"), "{out}");
    assert!(
        out.contains("pub fn note(org: impl RowRef<Id<entity::Org>>) -> NoteFixture"),
        "{out}"
    );
    assert!(out.contains("pub struct NoteRow"), "{out}");
    assert!(out.contains("pub fn reviewer(mut self, value: impl RowRef<Id<entity::Org>>)"));
    assert!(out.contains("format!(\"title-{n}\")"), "{out}");
    assert!(out.contains("pub fn on_shard(mut self"), "{out}");
    assert!(
        out.contains("impl FixtureTransport for Embedded<'_>"),
        "{out}"
    );
    assert!(
        !out.contains("pub struct MeshRow"),
        "ineligible models get no builder"
    );

    let wire = client_with(
        &schema,
        &decls,
        ClientTarget::Rust,
        ClientOptions::default(),
    );
    assert!(wire.contains("pub mod fixtures {"), "{wire}");
    assert!(wire.contains("pub fn connect(options: Connect)"), "{wire}");
    assert!(
        !wire.contains("based_runtime"),
        "a wire client never names the engine"
    );
}

#[test]
fn typescript_fixtures_mirror_the_rust_builders() {
    let (schema, _) = schema();
    let out = typescript_fixtures(&schema);
    assert!(
        out.starts_with("// Generated by `based gen fixtures`"),
        "{out}"
    );
    assert!(
        out.contains("export function note(org: OrgRef): NoteFixture"),
        "{out}"
    );
    assert!(out.contains("export interface NoteRow"), "{out}");
    assert!(out.contains("  reviewer(value: OrgRef): this {"), "{out}");
    assert!(out.contains("\"title\": `title-${n}`"), "{out}");
    assert!(
        out.contains("export type Tier = \"free\" | \"pro\";"),
        "{out}"
    );
    assert!(out.contains("function date(n: number)"), "{out}");
    assert!(
        !out.contains("function uuid("),
        "unused helpers are left out"
    );
    assert!(out.contains("export function connect("), "{out}");
    assert!(out.contains("export class Counter"), "{out}");
    assert!(out.contains("on_shard(key: string): this"), "{out}");
}

#[test]
fn every_emitted_allow_carries_a_reason() {
    let (schema, decls) = schema();
    let options = ClientOptions {
        embedded: true,
        dialect: Some(based_codegen::Dialect::Postgres),
    };
    let out = client_with(&schema, &decls, ClientTarget::Rust, options);
    let allows: Vec<_> = out
        .lines()
        .filter(|line| line.trim_start().starts_with("#[allow("))
        .collect();
    assert!(allows.len() > 5, "{out}");
    for allow in allows {
        assert!(allow.contains("reason = \""), "{allow}");
    }
}
