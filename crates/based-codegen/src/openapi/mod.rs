//! OpenAPI codegen (`based gen openapi`): a `CheckedSchema` + AST -> one OpenAPI 3.1
//! document (pretty JSON) describing the JSON/HTTP wire `serve::dispatch` serves — one
//! `POST /q|/m/<name>` path per callable, one `components.schemas` entry per input/output
//! type. Documents the existing wire; invents no endpoint or shape. Mirrors the `client`
//! emitter so routes and schema names stay in lockstep.

