//! The structural reverse of a migration and its canonical `down.mig` text: the diff from the
//! post-up snapshot back to the prior one, in the `up.mig` step vocabulary.

use super::diff::{diff_snapshots, Step};
use super::model::{Rename, Snapshot};
use super::script::FORMAT_MARKER;
use super::up_mig::render_step;

/// The steps undoing the migration from `prev` to `now`, in the order up's are undone:
/// constraints and indexes come off before the columns they cover, and go back on after.
pub fn down_steps(prev: &Snapshot, now: &Snapshot) -> Vec<Step> {
    let mut steps = diff_snapshots(now, &rollback_target(prev, now));
    steps.sort_by_key(phase);
    steps
}

fn phase(step: &Step) -> u8 {
    match step {
        Step::DropForeignKey { .. } => 0,
        Step::DropIndex { .. } | Step::DropUnique { .. } => 1,
        Step::AddIndex { .. } | Step::AddUnique { .. } => 3,
        Step::AddForeignKey { .. } => 4,
        _ => 2,
    }
}

/// `prev` carrying the inverse of `now`'s renames, so a rename reverses as a rename rather
/// than a drop + add.
pub(crate) fn rollback_target(prev: &Snapshot, now: &Snapshot) -> Snapshot {
    let table_back = |name: &str| {
        now.renames
            .iter()
            .find_map(|r| match r {
                Rename::Table { from, to } if to == name => Some(from.clone()),
                _ => None,
            })
            .unwrap_or_else(|| name.to_string())
    };
    let mut renames: Vec<Rename> = now
        .renames
        .iter()
        .map(|r| match r {
            Rename::Table { from, to } => Rename::Table {
                from: to.clone(),
                to: from.clone(),
            },
            Rename::Column { table, from, to } => Rename::Column {
                table: table_back(table),
                from: to.clone(),
                to: from.clone(),
            },
        })
        .collect();
    renames.sort();
    Snapshot {
        renames,
        ..prev.clone()
    }
}

/// Render the canonical `down.mig` for the migration from `prev` to `now`: a `format 2`
/// script of the reverse structural steps. Data steps and `raw(<dialect>)` lines may be
/// added between them.
pub fn render_down(prev: &Snapshot, now: &Snapshot) -> String {
    render_down_steps(&down_steps(prev, now))
}

/// The canonical `down.mig` text for already-computed reverse steps.
pub(crate) fn render_down_steps(steps: &[Step]) -> String {
    let mut out = String::from(DOWN_HEADER);
    out.push_str(FORMAT_MARKER);
    out.push('\n');
    for s in steps {
        render_step(&mut out, s);
    }
    out
}

const DOWN_HEADER: &str = "\
# down.mig — generated by `based migrate gen`: the reverse of up.mig, run by
# `based migrate apply --down`.
#
# The structural steps below are derived from the two schema.snap files; `apply` refuses a
# down.mig whose structural lines diverge from them. Every line runs in the order written.
# A reverse can restore a dropped column's shape but not its data. What you CAN add between
# the steps: data steps over the table and column names as of that line, and
# raw(<dialect>) `<sql>` lines.
";
