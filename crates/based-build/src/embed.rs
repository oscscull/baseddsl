//! Emit `OUT_DIR/schema.rs`: the manifest, sources and migrations as `include_str!`
//! constants, so `Compiled::from_sources` and `migrate::from_sources` run without a source
//! tree at runtime.
use crate::Error;
use based_manifest::Project;
use based_project::MigrationFiles;
use std::fmt::Write as _;
use std::path::Path;

pub(super) fn write(
    project: &Project,
    migrations: &[MigrationFiles],
    root: &Path,
    out: &Path,
) -> Result<(), Error> {
    let path = out.join("schema.rs");
    let text = render(project, migrations, root);
    if std::fs::read(&path).ok().as_deref() != Some(text.as_bytes()) {
        std::fs::write(&path, text)?;
    }
    Ok(())
}

fn render(project: &Project, migrations: &[MigrationFiles], root: &Path) -> String {
    let manifest = root.join(based_manifest::MANIFEST_NAME);
    let mut text = String::from("// Generated by based-build; embeds the checked schema.\n");
    let _ = writeln!(
        text,
        "pub const MANIFEST: &str = include_str!({:?});",
        manifest.display().to_string()
    );
    text.push_str("pub const SOURCES: &[(&str, &str)] = &[\n");
    for file in &project.files {
        let name = file.path.strip_prefix(root).unwrap_or(&file.path);
        let _ = writeln!(
            text,
            "    ({:?}, include_str!({:?})),",
            name.display().to_string(),
            file.path.display().to_string()
        );
    }
    text.push_str("];\n");
    text.push_str(&render_migrations(migrations));
    text
}

fn render_migrations(migrations: &[MigrationFiles]) -> String {
    let mut text = String::from(
        "#[allow(dead_code)]\n\
         pub const MIGRATIONS: &[based_runtime::migrate::MigrationSource<'static>] = &[\n",
    );
    for migration in migrations {
        let file = |name: &str| {
            format!(
                "include_str!({:?})",
                migration.dir.join(name).display().to_string()
            )
        };
        let down = migration.down.as_ref().map_or_else(
            || "None".to_string(),
            |_| format!("Some({})", file("down.mig")),
        );
        let _ = writeln!(
            text,
            "    based_runtime::migrate::MigrationSource {{ id: {:?}, up: {}, down: {down}, snapshot: {} }},",
            migration.id,
            file("up.mig"),
            file("schema.snap"),
        );
    }
    text.push_str("];\n");
    text
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::path::PathBuf;

    #[test]
    fn migrations_embed_each_file_with_an_optional_down() {
        let migration = |id: &str, down: bool| MigrationFiles {
            number: 0,
            id: id.into(),
            dir: PathBuf::from("/app/migrations").join(id),
            up: String::new(),
            down: down.then(String::new),
            snapshot: String::new(),
        };
        let text =
            render_migrations(&[migration("0001_init", false), migration("0002_more", true)]);
        assert!(text.contains(
            "MigrationSource { id: \"0001_init\", up: include_str!(\"/app/migrations/0001_init/up.mig\"), down: None, snapshot: include_str!(\"/app/migrations/0001_init/schema.snap\") },"
        ), "{text}");
        assert!(
            text.contains("down: Some(include_str!(\"/app/migrations/0002_more/down.mig\"))"),
            "{text}"
        );
    }
}
