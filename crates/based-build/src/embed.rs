//! Emit `OUT_DIR/schema.rs`: the manifest and sources as `include_str!` constants,
//! so `Compiled::from_sources` runs without a source tree at runtime.
use crate::Error;
use based_manifest::Project;
use std::fmt::Write as _;
use std::path::Path;

pub(super) fn write(project: &Project, root: &Path, out: &Path) -> Result<(), Error> {
    let path = out.join("schema.rs");
    let text = render(project, root);
    if std::fs::read(&path).ok().as_deref() != Some(text.as_bytes()) {
        std::fs::write(&path, text)?;
    }
    Ok(())
}

fn render(project: &Project, root: &Path) -> String {
    let manifest = root.join(based_manifest::MANIFEST_NAME);
    let mut text = String::from("// Generated by based-build; embeds the checked schema.\n");
    let _ = writeln!(
        text,
        "pub const MANIFEST: &str = include_str!({:?});",
        manifest.display().to_string()
    );
    text.push_str("pub const SOURCES: &[(&str, &str)] = &[\n");
    for file in &project.files {
        let name = file.path.strip_prefix(root).unwrap_or(&file.path);
        let _ = writeln!(
            text,
            "    ({:?}, include_str!({:?})),",
            name.display().to_string(),
            file.path.display().to_string()
        );
    }
    text.push_str("];\n");
    text
}
